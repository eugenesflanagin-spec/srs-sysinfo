#!/usr/bin/env python3
"""Generate sec_stubs.c (one srs_item per SIV item) from CHECKLIST.tsv, or from a plain
item list when the checklist is not there yet. Real producers in sec_<group>.c override
these by id, so every SIV item is addressable even before it is implemented."""
import csv
import sys

src, out = sys.argv[1], sys.argv[2]


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


rows = []
if src.endswith('.tsv'):
    with open(src, encoding='utf-8') as f:
        for r in csv.DictReader(f, delimiter='\t'):
            rows.append(r)
else:
    for line in open(src, encoding='utf-8'):
        line = line.strip().strip('[]')
        if line:
            rows.append({'id': line, 'category': 'hardware', 'title': line, 'bucket': 'LINUX',
                         'needs_root': 'no', 'linux_source': 'pending classification', 'group': 'siv'})

bucket = {'LINUX': 'B_LINUX', 'ABSENT': 'B_ABSENT', 'WINONLY': 'B_WINONLY'}
with open(out, 'w', encoding='utf-8') as f:
    f.write('/* generated by gen_stubs.py from %s - do not edit */\n#include "sec.h"\n\n' % src.split('/')[-1])
    f.write('const srs_item sec_stubs[] = {\n')
    for r in rows:
        f.write('    { %s, %s, %s, %s, %d, %s, NULL, 0, %s },\n' % (
            cstr(r['id']), cstr(r.get('category') or 'hardware'), cstr(r.get('title') or r['id']),
            bucket.get((r.get('bucket') or 'LINUX').strip().upper(), 'B_LINUX'),
            1 if (r.get('needs_root') or '').lower().startswith('y') else 0,
            cstr(r.get('linux_source') or ''), cstr(r.get('group') or 'siv')))
    f.write('    { NULL, NULL, NULL, B_LINUX, 0, NULL, NULL, 0, NULL }\n};\n')
print('%d items -> %s' % (len(rows), out))
