#!/usr/bin/env bash
# shaders/gpu/build.sh - compile the GPU benchmark's GLSL compute shaders to SPIR-V and write them
# as C uint32_t arrays into bench_gpu_spv.inc (committed, so building SRS needs no shader tools).
#
#   shaders/gpu/build.sh           regenerate bench_gpu_spv.inc
#   shaders/gpu/build.sh --check   fail if the committed bench_gpu_spv.inc is not what the
#                                  sources compile to (stale), change nothing
#
# Needs glslangValidator (glslang) and, for validation, spirv-val (spirv-tools).
# Target: Vulkan 1.1 / SPIR-V 1.3 (the benchmark needs a Vulkan 1.1 device).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
top=$(cd "$here/../.." && pwd)
out=$top/bench_gpu_spv.inc
check=0
[ "${1:-}" = --check ] && check=1
command -v glslangValidator >/dev/null || { echo "glslangValidator not found (install glslang)"; exit 2; }
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
names="fma32 fma16 fma64 imad32 mem_write mem_read mem_copy tick gemm32 gemm64 gemm16 cmp gemm32b gemm64b"
{
    echo "/* bench_gpu_spv.inc - SPIR-V of the GPU benchmark's compute shaders (the .comp files in shaders/gpu)."
    echo " * GENERATED by shaders/gpu/build.sh - do not edit; edit the .comp sources and rerun it."
    echo " * glslangValidator --target-env vulkan1.1, entry point \"main\". */"
    for n in $names; do
        glslangValidator -V --target-env vulkan1.1 -o "$tmp/$n.spv" "$here/$n.comp" >/dev/null 2>&1 \
            || { glslangValidator -V --target-env vulkan1.1 -o "$tmp/$n.spv" "$here/$n.comp"; exit 1; }
        if command -v spirv-val >/dev/null; then spirv-val --target-env vulkan1.1 "$tmp/$n.spv"; fi
        echo "static const uint32_t spv_$n[] = {"
        od -An -v -tx4 -w16 "$tmp/$n.spv" | sed -e 's/^ *//' -e 's/ \+/, /g' -e 's/\([0-9a-f]\{8\}\)/0x\1/g' -e 's/^/    /' -e 's/$/,/'
        echo "};"
    done
} > "$tmp/spv.inc"
if [ $check = 1 ]; then
    cmp -s "$tmp/spv.inc" "$out" && { echo "bench_gpu_spv.inc is up to date"; exit 0; }
    echo "bench_gpu_spv.inc is STALE: run shaders/gpu/build.sh"; exit 1
fi
cp "$tmp/spv.inc" "$out"
echo "wrote $out ($(grep -c '^static' "$out") shaders)"
