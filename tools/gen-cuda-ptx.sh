#!/usr/bin/env bash
# tools/gen-cuda-ptx.sh - precompile SRS's own CUDA kernels (gpu_kernels.h, the same source text NVRTC builds)
# to PTX with clang, and write them as C strings into gpu_kernels_ptx.inc (committed, so building SRS needs
# no CUDA tools at all; `make cuda-ptx` runs this).
#
#   tools/gen-cuda-ptx.sh           regenerate gpu_kernels_ptx.inc
#   tools/gen-cuda-ptx.sh --check   fail (exit 1) if the committed gpu_kernels_ptx.inc is not what this clang makes
#                                   of the current source; exit 3 (not compared) when the .inc was made by another
#                                   clang version, whose output may differ for harmless reasons
#
# Needs: clang with the NVPTX target (clang -print-targets lists nvptx64) and gcc. NO NVIDIA toolkit:
# -nocudainc -nocudalib, the kernels use clang's own builtins (the GKD_PTX preamble in gpu_kernels.h).
#
# Target, chosen to be accepted as widely as possible:
#   .target sm_50  - the oldest GPU generation (Maxwell) current CUDA drivers still run; the driver compiles
#                    PTX for sm_50 on to any newer GPU when the module is loaded (PTX is forward compatible)
#   .version 6.0   - PTX ISA 6.0 = CUDA 9.0 drivers (2017) and newer; every instruction used here exists there.
#                    clang otherwise writes the newest PTX ISA it knows, which older drivers refuse.
#   -ffp-contract=off  no fused multiply-add the source did not ask for (the results are checked exactly)
set -euo pipefail
SM=sm_50
PTX=ptx60
PTXVER=6.0
top=$(cd "$(dirname "$0")/.." && pwd)
out=$top/gpu_kernels_ptx.inc
check=0
[ "${1:-}" = --check ] && check=1
CLANG=${CLANG:-/usr/bin/clang}
[ -x "$CLANG" ] || CLANG=$(command -v clang || true)
[ -n "$CLANG" ] && "$CLANG" -print-targets 2>/dev/null | grep -q nvptx64 || { echo "clang with the NVPTX target not found"; exit 2; }
cver=$("$CLANG" --version | head -1)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
cat > "$tmp/emit.c" <<'C'
#include "gpu_kernels.h"
int main(int argc, char **argv)
{
    char *s = gk_source(GKD_PTX, argc > 1 && argv[1][0] == '1');
    if (!s) return 1;
    fputs(s, stdout);
    free(s);
    return 0;
}
C
/usr/bin/gcc -std=c11 -Wall -Wextra -I"$top" -o "$tmp/emit" "$tmp/emit.c"
flags=(-x cuda --cuda-device-only --cuda-gpu-arch=$SM -nocudainc -nocudalib -O2 -ffp-contract=off -fno-exceptions)
# clang turns on its newest PTX feature by default; switch that one off and PTX 6.0 on
"$tmp/emit" 0 > "$tmp/k0.cu"
def=$("$CLANG" "${flags[@]}" -S -emit-llvm -o - "$tmp/k0.cu" | grep -o '+ptx[0-9]*' | head -1)
feat=(-Xclang -target-feature -Xclang +$PTX)
[ -n "$def" ] && [ "$def" != "+$PTX" ] && feat=(-Xclang -target-feature -Xclang "-${def#+}" "${feat[@]}")
{
    echo "/* gpu_kernels_ptx.inc - SRS's own CUDA kernels (gpu_kernels.h) precompiled to PTX, one string per precision."
    echo " * GENERATED by tools/gen-cuda-ptx.sh (make cuda-ptx) - do not edit; edit gpu_kernels.h and rerun it."
    echo " * clang -x cuda --cuda-device-only --cuda-gpu-arch=$SM, PTX ISA $PTXVER, no CUDA headers or libraries."
    echo " * made by: $cver"
    echo " * Loaded with cuModuleLoadData by gpuburn_rt.c; the kernel names and parameters are those NVRTC builds. */"
    for fp in 0 1; do
        name=$([ $fp = 1 ] && echo fp64 || echo fp32)
        "$tmp/emit" $fp > "$tmp/k$fp.cu"
        "$CLANG" "${flags[@]}" "${feat[@]}" -S -o "$tmp/k$fp.ptx" "$tmp/k$fp.cu"
        grep -q "^\.version $PTXVER\$" "$tmp/k$fp.ptx" || { echo "clang did not write PTX ISA $PTXVER"; exit 1; }
        if grep -qE '^\s*(call|\.extern)' "$tmp/k$fp.ptx"; then echo "the PTX calls an outside function (a missing builtin?)"; exit 1; fi
        echo "static const char gk_ptx_$name[] ="
        echo "    \"// SRS own kernels, $(echo $name | tr a-z A-Z)\\n\""
        sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/\t/\\t/g' -e 's/^/    "/' -e 's/$/\\n"/' "$tmp/k$fp.ptx"
        echo "    ;"
    done
} > "$tmp/ptx.inc"
if [ $check = 1 ]; then
    if ! grep -qxF " * made by: $cver" "$out"; then
        echo "gpu_kernels_ptx.inc was made by $(sed -n 's/^ \* made by: //p' "$out"), this is $cver: not compared"; exit 3
    fi
    cmp -s "$tmp/ptx.inc" "$out" && { echo "gpu_kernels_ptx.inc is up to date"; exit 0; }
    echo "gpu_kernels_ptx.inc is STALE: run make cuda-ptx"; exit 1
fi
cp "$tmp/ptx.inc" "$out"
echo "wrote $out ($(grep -c '^static' "$out") PTX modules)"
